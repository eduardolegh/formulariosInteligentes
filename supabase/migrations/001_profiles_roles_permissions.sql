create or replace function public.has_permission(permission_key text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.role_permissions rp on rp.role_id = ur.role_id
    join public.permissions p on p.id = rp.permission_id
    where ur.user_id = auth.uid() and p.key = permission_key
  );
$$;

create or replace function public.has_permission_for_user(target_user_id uuid, permission_key text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.role_permissions rp on rp.role_id = ur.role_id
    join public.permissions p on p.id = rp.permission_id
    where ur.user_id = target_user_id and p.key = permission_key
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.roles enable row level security;
alter table public.permissions enable row level security;
alter table public.role_permissions enable row level security;
alter table public.user_roles enable row level security;

create policy "profiles: self or manager can read"
  on public.profiles for select to authenticated
  using (id = auth.uid() or public.has_permission('users.manage'));

create policy "profiles: self or manager can update"
  on public.profiles for update to authenticated
  using (id = auth.uid() or public.has_permission('users.manage'))
  with check (id = auth.uid() or public.has_permission('users.manage'));

create policy "roles: authenticated users can read"
  on public.roles for select to authenticated using (true);

create policy "permissions: authenticated users can read"
  on public.permissions for select to authenticated using (true);

create policy "role permissions: authenticated users can read"
  on public.role_permissions for select to authenticated using (true);

create policy "user roles: self or manager can read"
  on public.user_roles for select to authenticated
  using (user_id = auth.uid() or public.has_permission('users.manage'));

create policy "user roles: manager can insert"
  on public.user_roles for insert to authenticated
  with check (public.has_permission('roles.manage'));

create policy "user roles: manager can delete"
  on public.user_roles for delete to authenticated
  using (public.has_permission('roles.manage'));
