-- Métricas operativas, historial de estados y trazabilidad de análisis con IA.

alter table public.form_submissions
  add column if not exists review_started_at timestamptz,
  add column if not exists decided_at timestamptz;

create table if not exists public.submission_status_history (
  id bigint generated by default as identity primary key,
  submission_id uuid not null references public.form_submissions(id) on delete cascade,
  previous_status text,
  new_status text not null,
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

create index if not exists submission_status_history_submission_idx
  on public.submission_status_history (submission_id, changed_at);

create table if not exists public.ai_analysis_runs (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.form_submissions(id) on delete cascade,
  form_id uuid not null references public.forms(id) on delete cascade,
  requested_by uuid references auth.users(id) on delete set null,
  provider text not null default 'openai',
  model text not null,
  status text not null check (status in ('succeeded', 'failed')),
  started_at timestamptz not null,
  completed_at timestamptz not null,
  duration_ms integer not null check (duration_ms >= 0),
  input_tokens integer not null default 0 check (input_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  total_tokens integer not null default 0 check (total_tokens >= 0),
  estimated_cost_usd numeric(12, 6),
  suggested_status text check (suggested_status in ('approved', 'rejected')),
  confidence numeric(5, 4),
  observation text,
  provider_response_id text,
  error_message text,
  human_decision text check (human_decision in ('approved', 'rejected')),
  human_decided_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists ai_analysis_runs_form_started_idx
  on public.ai_analysis_runs (form_id, started_at desc);
create index if not exists ai_analysis_runs_submission_idx
  on public.ai_analysis_runs (submission_id, started_at desc);

create or replace function public.initialize_submission_status_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.submission_status_history
    (submission_id, previous_status, new_status, changed_by, changed_at)
  values (new.id, null, new.status, auth.uid(), new.submitted_at);
  return new;
end;
$$;

create or replace function public.track_submission_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status is distinct from old.status then
    if new.status = 'in_review' and old.status <> 'in_review' then
      new.review_started_at := now();
      new.decided_at := null;
    elsif new.status in ('approved', 'rejected') then
      new.review_started_at := coalesce(new.review_started_at, now());
      new.decided_at := now();
    end if;

    insert into public.submission_status_history
      (submission_id, previous_status, new_status, changed_by, changed_at)
    values (new.id, old.status, new.status, auth.uid(), now());

    if new.status in ('approved', 'rejected') then
      update public.ai_analysis_runs
      set human_decision = new.status,
          human_decided_at = now()
      where id = (
        select id
        from public.ai_analysis_runs
        where submission_id = new.id
          and status = 'succeeded'
          and human_decision is null
        order by completed_at desc
        limit 1
      );
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists track_submission_status_trigger on public.form_submissions;
create trigger track_submission_status_trigger
  before update of status on public.form_submissions
  for each row execute function public.track_submission_status();

drop trigger if exists initialize_submission_status_history_trigger on public.form_submissions;
create trigger initialize_submission_status_history_trigger
  after insert on public.form_submissions
  for each row execute function public.initialize_submission_status_history();

-- Punto de partida para registros creados antes de esta migración.
insert into public.submission_status_history
  (submission_id, previous_status, new_status, changed_at)
select fs.id, null, fs.status, fs.submitted_at
from public.form_submissions fs
where not exists (
  select 1 from public.submission_status_history h where h.submission_id = fs.id
);

update public.form_submissions
set review_started_at = coalesce(review_started_at, submitted_at)
where status in ('in_review', 'approved', 'rejected');

update public.form_submissions
set decided_at = coalesce(decided_at, submitted_at)
where status in ('approved', 'rejected');

alter table public.submission_status_history enable row level security;
alter table public.ai_analysis_runs enable row level security;

create policy "dashboard users can read status history"
  on public.submission_status_history for select to authenticated
  using (
    public.has_permission('dashboards.view')
    or exists (
      select 1 from public.form_submissions fs
      where fs.id = submission_id
        and (fs.submitted_by = auth.uid() or public.has_permission('forms.view') or public.has_permission('forms.inbox'))
    )
  );

create policy "dashboard users can read ai metrics"
  on public.ai_analysis_runs for select to authenticated
  using (
    public.has_permission('dashboards.view')
    or public.has_permission('forms.view')
    or public.has_permission('forms.inbox')
  );

